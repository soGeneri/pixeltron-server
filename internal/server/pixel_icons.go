// tmplPixelIcon renders a pixel icon at a whole-number scale (1–8, default 2).
// Unknown names render nothing so a typo never breaks a page.
func tmplPixelIcon(name string, scale ...int) template.HTML {
	rows, ok := pixelIcons[name]
	if !ok {
		return ""
	}
	s := 2
	if len(scale) > 0 {
		s = min(max(scale[0], 1), 8)
	}
	var b strings.Builder
	fmt.Fprintf(&b, `<svg class="ttp-icon" width="%d" height="%d" viewBox="0 0 8 8" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">`, 8*s, 8*s)
	for y, row := range rows {
		for x := 0; x < len(row); {
			if row[x] != '#' {
				x++
				continue
			}
			start := x
			for x < len(row) && row[x] == '#' {
				x++
			}
			fmt.Fprintf(&b, `<rect x="%d" y="%d" width="%d" height="1"/>`, start, y, x-start)
		}
	}
	b.WriteString(`</svg>`)
	return template.HTML(b.String()) //nolint:gosec // built only from the fixed bitmaps above
}
